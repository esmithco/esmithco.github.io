"""Nov 20: 'Which capture?' bank. He picks the even trade instead of the one that wins material, and loses count in long trades.
Positions (Lichess puzzle DB, CC0, rating 900-1700) where it's your move and there are 2-4 captures: one wins >= 2 points after the
recaptures (engine line, measured after the opponent's reply), and at least one other is only an even trade (-1..+1).
Rows: [fen, [[san, material after the line, 'line SAN'], ...] sorted best first, rating]. Usage: python trades.py <out trades.js>"""
import csv,io,json,subprocess,sys,random,chess,chess.engine
from multiprocessing import Pool
random.seed(11)
V={1:1,2:3,3:3,4:5,5:9,6:0}
def bal(b,c):return sum((1 if p.color==c else -1)*V[p.piece_type] for p in b.piece_map().values())
def work(x):
    fen,r=x;e=chess.engine.SimpleEngine.popen_uci('/opt/homebrew/bin/stockfish')
    try:
        b=chess.Board(fen);col=b.turn;b0=bal(b,col);caps=[m for m in b.legal_moves if b.is_capture(m)]
        if not 2<=len(caps)<=4:return None
        out=[]
        for m in caps:
            c=b.copy();san=c.san(m);c.push(m);line=[san]
            if c.is_checkmate():out.append([san,99,san]);continue
            info=e.analyse(c,chess.engine.Limit(depth=11));pv=info.get('pv',[])[:5];last=None;d=c.copy()
            for i,mv in enumerate(pv):
                line.append(d.san(mv));d.push(mv)
                if d.is_checkmate():last=-99 if d.turn==col else 99;break
                if i%2==0:last=bal(d,col)-b0      # after the opponent's reply
            if last is None:last=bal(c,col)-b0
            out.append([san,last,' '.join(line)])
        out.sort(key=lambda o:-o[1]);best=out[0][1]
        if best<2 or best>=99 and False:return None
        if len(out)>1 and out[1][1]>=best-1:return None                 # the best capture must stand out
        if not any(-1<=o[1]<=1 for o in out[1:]):return None              # and an even trade must be there to tempt him
        return [fen,out,r]
    except Exception:return None
    finally:e.quit()
if __name__=='__main__':
    p=subprocess.Popen(['zstd','-dc','lichess_db_puzzle.csv.zst'],stdout=subprocess.PIPE);rd=csv.reader(io.TextIOWrapper(p.stdout,encoding='utf-8'));next(rd);cand=[]
    for row in rd:
        pid,fen,moves,rating,_,pop,plays,themes=row[:8];rating=int(rating)
        if not 900<=rating<=1700 or int(pop)<85 or int(plays)<500:continue
        mv=moves.split();b=chess.Board(fen);b.push(chess.Move.from_uci(mv[0]))
        sol=chess.Move.from_uci(mv[1])
        if not b.is_capture(sol) or b.is_check():continue
        n=sum(1 for m in b.legal_moves if b.is_capture(m))
        if 2<=n<=4:cand.append((b.fen(),rating))
        if len(cand)>=9000:break
    p.kill();random.shuffle(cand);print('candidates',len(cand),flush=True)
    with Pool(7) as pool:res=[x for x in pool.map(work,cand[:5000],chunksize=10) if x]
    res=res[:450];res.sort(key=lambda x:x[2])
    open(sys.argv[1],'w').write('/* Generated by tools/trades.py (Lichess puzzle DB, CC0): "which capture?" positions. Rows: [fen, [[san, material after the line, line], ...best first], rating]. */\nwindow.TRADES='+json.dumps(res,ensure_ascii=False,separators=(',',':'))+';\n')
    print('kept',len(res))
