# Builds ../debiles.js: the big weak-spot bank (Nov 17). Lichess puzzle DB (CC0), grouped by HIS weak themes
# (same keys as THEMES in app.js), rating 850-1900, popular puzzles only, course puzzles excluded (they stay in Aprender).
# Usage (scratch dir with lichess_db_puzzle.csv.zst + python-chess): python weak.py <path>/curso.js <path>/debiles.js
import csv, io, json, subprocess, sys, random, chess
random.seed(7)
src = open(sys.argv[1]).read(); course = json.loads(src[src.index('{'):src.rstrip().rstrip(';').rindex('}') + 1])
skip = {p['id'] for l in course['lessons'] for p in l.get('p', [])}
G = {  # key: (lichess themes any-of, extra filter, size)
 'hang':  ({'hangingPiece', 'defensiveMove'}, None, 450),
 'forkd': ({'fork'}, None, 450),
 'lines': ({'pin', 'skewer', 'discoveredAttack', 'xRayAttack'}, None, 450),
 'matek': ({'mateIn2', 'mateIn3', 'backRankMate', 'kingsideAttack', 'attackingF2F7'}, 'queen', 700),
 'calc':  ({'advantage', 'crushing', 'mateIn2', 'mateIn3', 'mateIn4', 'quietMove', 'intermezzo', 'sacrifice'}, 'long', 600),
 # drill banks (Nov 19: Flash showed the same mate again and again): short, easy positions for Flash / Rush / Defense / Game mode
 'd_mate1': ({'mateIn1'}, 'easy', 700),
 'd_hang':  ({'hangingPiece'}, 'easy', 700),
 'd_fork':  ({'fork'}, 'easy', 400),
 'd_back':  ({'backRankMate'}, 'easy', 400),
 'd_mate2': ({'mateIn2'}, 'easy', 400),
}
pools = {k: [] for k in G}
p = subprocess.Popen(['zstd', '-dc', 'lichess_db_puzzle.csv.zst'], stdout=subprocess.PIPE)
rd = csv.reader(io.TextIOWrapper(p.stdout, encoding='utf-8'))
next(rd)
for r in rd:
    pid, fen, moves, rating, rd_, pop, plays, themes = r[:8]
    rating, pop, plays = int(rating), int(pop), int(plays)
    if pid in skip or rating < 850 or rating > 1900 or pop < 85 or plays < 800: continue
    th = set(themes.split()); mv = moves.split()
    if 'veryLong' in th or len(mv) > 8: continue
    for k, (want, extra, n) in G.items():
        if not (th & want): continue
        if extra != 'easy' and 'mateIn1' in th: continue
        if extra == 'easy' and (rating > 1500 or len(mv) > 4): continue
        if extra == 'long' and len(mv) not in (4, 6, 8): continue
        pools[k].append((pid, fen, mv, rating))
p.kill()
def san(fen, mv):
    b = chess.Board(fen); out = []
    for u in mv:
        m = chess.Move.from_uci(u); out.append(b.san(m)); b.push(m)
    return out
out = {}
for k, (want, extra, n) in G.items():
    L = pools[k]; random.shuffle(L)
    # spread over rating bands so there is always something at his level
    bands = {}
    for x in L: bands.setdefault(min(x[3] // 150, 12), []).append(x)
    per = max(1, n // max(1, len(bands))); sel = []
    for b in sorted(bands): sel += bands[b][:per]
    rows = []
    for pid, fen, mv, r in sel:
        s = san(fen, mv)
        if extra == 'queen' and not any(x.startswith('Q') for x in s[1::2]): continue
        rows.append([pid, fen, ' '.join(s), r])
    rows.sort(key=lambda x: x[3]); out[k] = rows
    print(k, len(pools[k]), '->', len(rows))
open(sys.argv[2], 'w').write('/* Generated by tools/weak.py from the Lichess puzzle database (CC0). Rows: [id, fen before the opponent move, SAN moves, rating]. */\nwindow.WEAKDB=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
