# Sacrifices (Nov 23, his words: "a good sacrifice is really difficult to see"). A move is a SACRIFICE when, right after it, the
# opponent has a legal capture of the moved piece and the piece is worth >= 2 more than what it took (Bxh7+, Nxf7, Rxd5 exchange sac,
# a piece put on an attacked square).
#   python sacs.py games <dir with g10.json g11.json> <out json>   -> moments in HIS games where the best move was a sacrifice he missed
#   python sacs.py lichess <curso.js> <debiles.js> <out sacrificios.js>  (run where lichess_db_puzzle.csv.zst is)
import json, io, sys, csv, subprocess, random, chess, chess.pgn, chess.engine
from multiprocessing import Pool
V = {1: 1, 2: 3, 3: 3, 4: 5, 5: 9, 6: 0}
def is_sac(b, m):
    p = b.piece_at(m.from_square)
    if p is None or p.piece_type in (chess.KING, chess.PAWN): return False
    cap = b.piece_at(m.to_square); got = V[cap.piece_type] if cap else 0
    if V[p.piece_type] - got < 2: return False
    b2 = b.copy(); b2.push(m)
    return any(x.to_square == m.to_square for x in b2.legal_moves)
def game(g):
    e = chess.engine.SimpleEngine.popen_uci('/opt/homebrew/bin/stockfish'); out = []
    try:
        pg = chess.pgn.read_game(io.StringIO(g['pgn'])); col = chess.WHITE if g['white']['username'].lower() == 'esmithco' else chess.BLACK
        b = pg.board(); prev = None
        for ply, nd in enumerate(pg.mainline()):
            m = nd.move
            if b.turn == col and ply >= 10:
                i = e.analyse(b, chess.engine.Limit(depth=12))
                best = i['pv'][0]
                if best != m and is_sac(b, best):
                    sb = i['score'].pov(col).score(mate_score=3000)
                    b2 = b.copy(); b2.push(m); sm = -e.analyse(b2, chess.engine.Limit(depth=12))['score'].pov(b2.turn).score(mate_score=3000)
                    if sb >= 150 and sb - sm >= 150:
                        d = e.analyse(b, chess.engine.Limit(depth=16), multipv=2)
                        if d[0]['pv'][0] == best:
                            s0 = d[0]['score'].pov(col).score(mate_score=3000)
                            s2 = d[1]['score'].pov(col).score(mate_score=3000) if len(d) > 1 else -9999
                            if s0 >= 150 and s0 - s2 >= 100:
                                c = b.copy(); pv = []
                                for x in d[0]['pv'][:6]: pv.append(c.san(x)); c.push(x)
                                out.append([b.fen(), s0, pv[0], ' '.join(pv), prev, g['end_time'], [], 1, b.san(m)])
            prev = b.fen(); b.push(m)
    except Exception: pass
    finally: e.quit()
    return out
if __name__ == '__main__':
    if sys.argv[1] == 'games':
        G = []
        for f in ['g10.json', 'g11.json']: G += json.load(open(sys.argv[2] + '/' + f))['games']
        G = [g for g in G if g.get('time_class') == 'rapid' and g['end_time'] >= 1790830800]
        with Pool(7) as p: R = p.map(game, G, chunksize=2)
        rows = [r for x in R for r in x]; json.dump(rows, open(sys.argv[3], 'w')); print('missed sacrifices', len(rows))
    else:
        import re
        skip = set(re.findall(r'"([A-Za-z0-9]{5})"', open(sys.argv[2]).read() + open(sys.argv[3]).read()))
        p = subprocess.Popen(['zstd', '-dc', 'lichess_db_puzzle.csv.zst'], stdout=subprocess.PIPE)
        rd = csv.reader(io.TextIOWrapper(p.stdout, encoding='utf-8')); next(rd); pool = []
        for r in rd:
            pid, fen, moves, rating, rd_, pop, plays, themes = r[:8]
            rating, pop, plays = int(rating), int(pop), int(plays)
            if pid in skip or rating < 900 or rating > 1850 or pop < 80 or plays < 500: continue
            mv = moves.split(); th = set(themes.split())
            if len(mv) > 8 or 'mateIn1' in th: continue
            b = chess.Board(fen); b.push_uci(mv[0]); m = chess.Move.from_uci(mv[1])
            if not is_sac(b, m): continue
            pool.append((pid, fen, mv, rating))
        p.kill(); random.seed(5); random.shuffle(pool); bands = {}
        for x in pool: bands.setdefault(min(x[3] // 100, 20), []).append(x)
        sel = []
        for k in sorted(bands): sel += bands[k][:50]
        def san(fen, mv):
            b = chess.Board(fen); o = []
            for u in mv: x = chess.Move.from_uci(u); o.append(b.san(x)); b.push(x)
            return o
        rows = sorted([[pid, fen, ' '.join(san(fen, mv)), r] for pid, fen, mv, r in sel], key=lambda x: x[3])
        print('pool', len(pool), '-> kept', len(rows))
        open(sys.argv[4], 'w').write('/* Generated by tools/sacs.py from the Lichess puzzle database (CC0): the first move is a sacrifice (the piece can be taken and is worth >= 2 more than what it took). Rows: [id, fen before the opponent move, SAN moves, rating]. */\nwindow.WEAKDB=window.WEAKDB||{};WEAKDB.sac=' + json.dumps(rows, separators=(',', ':')) + ';\n')
