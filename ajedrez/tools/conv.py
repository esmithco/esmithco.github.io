"""Nov 19: 'Remata' bank — moments from HIS games where he was winning (>= +5) — 1 in 3 of those games he still lost or drew
(33 of the 55 losses on time). Per game: the move where he threw it away (if any) plus one more winning moment. Engine best line at depth 14.
Usage (scratch dir with full.json from the game review + g09/g10/g11.json Chess.com archives): python conv.py <dir> <out conv.js>"""
import json,sys,io,random,chess,chess.pgn,chess.engine
from multiprocessing import Pool
random.seed(3)
def work(x):
    e=chess.engine.SimpleEngine.popen_uci('/opt/homebrew/bin/stockfish')
    try:
        b=chess.Board(x['fen']);r=e.analyse(b,chess.engine.Limit(depth=14),multipv=3)
        s=r[0]['score'].pov(b.turn).score(mate_score=10000);pv=[];c=b.copy()
        for m in r[0]['pv'][:6]:pv.append(c.san(m));c.push(m)
        good=[b.san(i['pv'][0]) for i in r if i['score'].pov(b.turn).score(mate_score=10000)>=300]
        return [x['fen'],s,pv[0] if pv else '',' '.join(pv),x['thrown'],x['date'],good,x.get('clk')]
    except Exception:return None
    finally:e.quit()
if __name__=='__main__':
    D=sys.argv[1];R=[r for r in json.load(open(D+'/full.json')) if 'mv' in r];G={}
    for m in ['09','10','11']:
        for g in json.load(open(D+'/g'+m+'.json'))['games']:G[g['url']]=g
    todo=[]
    for r in R:
        g=G.get(r['url'])
        if not g:continue
        win=[x for x in r['mv'] if x[2]>=500 and x[2]<5000]
        if not win:continue
        thrown=[x for x in r['mv'] if x[2]>=300 and x[3]<=50]
        low=[x for x in r['mv'] if x[2]>=300 and x[2]<5000 and x[5] is not None and x[5]<90]   # Nov 20: winning with little clock
        pick=([thrown[0]] if thrown else [])+[random.choice(win)]+(random.sample(low,min(2,len(low))) if low else [])
        pg=chess.pgn.read_game(io.StringIO(g['pgn']));b=pg.board();want={p[0]:p for p in pick};seen=set()
        for i,nd in enumerate(pg.mainline()):
            if i in want and i not in seen:
                seen.add(i);todo.append({'fen':b.fen(),'thrown':1 if thrown and want[i] is thrown[0] else 0,'date':r['end'],'clk':want[i][5]})
            b.push(nd.move)
    print('positions',len(todo),flush=True)
    with Pool(7) as p:out=[x for x in p.map(work,todo,chunksize=4) if x and x[1]>=300]
    open(sys.argv[2],'w').write('/* Generated by tools/conv.py: winning moments (>= +5) from his own games, engine line at depth 14. Rows: [fen, eval for him, best, pv, thrown(1 = he threw it away here), date, moves keeping >= +3, his clock in s]. */\nwindow.CONV='+json.dumps(out,separators=(',',':'))+';\n')
    print('kept',len(out),'thrown',sum(x[4] for x in out))
