"""Nov 24 (his idea: "how much I've played each opening, wins/draws/losses, the best and the worst"): every rapid game is put in the
repertoire SECTION (OPLAN plan group) of the deepest repertoire position it reached (at least 4 plies in). Counts all-time and for the
last 60 days, per opening, per section and per line. Usage: python ostats.py <rep.json from node> <dir with Chess.com archives> <out .js>"""
import json, sys, glob, io, time, chess, chess.pgn
R = json.load(open(sys.argv[1]))
def key(b): return ' '.join(b.fen().split()[:4])
maps = {}
for op, o in R.items():
    m = {}
    for i, mv in enumerate(o['lines']):
        if not mv: continue
        b = chess.Board()
        for p, s in enumerate(mv):
            b.push_san(s); k = key(b)
            if k not in m or m[k][1] < p + 1: m[k] = (i, p + 1)
    grp = {}
    for g in o['groups']:
        for i in g['g']: grp.setdefault(i, g['k'])
    maps[op] = (m, grp, o['side'])
G = []
for f in sorted(glob.glob(sys.argv[2] + '/20*.json')): G += json.load(open(f))['games']
G = [g for g in G if g.get('time_class') == 'rapid' and g.get('rules') == 'chess']
now = time.time(); recent = now - 60 * 86400
out = {op: {'all': [0, 0, 0], 'rec': [0, 0, 0], 'groups': {}, 'lines': {}} for op in R}
def add(d, k, res, rec):
    x = d.setdefault(k, {'all': [0, 0, 0], 'rec': [0, 0, 0]}); x['all'][res] += 1
    if rec: x['rec'][res] += 1
for g in G:
    me = 'w' if g['white']['username'].lower() == 'esmithco' else 'b'; mine = g['white'] if me == 'w' else g['black']
    other = g['black'] if me == 'w' else g['white']
    res = 0 if mine['result'] == 'win' else 2 if other['result'] == 'win' else 1          # 0 win, 1 draw, 2 loss
    try: pg = chess.pgn.read_game(io.StringIO(g['pgn']))
    except Exception: continue
    b = pg.board(); seen = []
    for p, mv in enumerate(pg.mainline_moves()):
        if p >= 24: break
        b.push(mv); seen.append(key(b))
    best = None
    for op, (m, _g, side) in maps.items():
        if side != me: continue
        for k in seen:
            if k in m and m[k][1] >= 4 and (best is None or m[k][1] > best[2]): best = (op, m[k][0], m[k][1])
    if not best: continue
    op, li, depth = best; rec = g['end_time'] >= recent; o = out[op]
    o['all'][res] += 1
    if rec: o['rec'][res] += 1
    add(o['groups'], maps[op][1].get(li, 'other'), res, rec); add(o['lines'], str(li), res, rec)
for op in out: print(op, 'all W/D/L', out[op]['all'], 'last 60d', out[op]['rec'], {k: v['all'] for k, v in out[op]['groups'].items()})
open(sys.argv[3], 'w').write('/* Generated by tools/ostats.py (%s): his rapid games per opening / section / line. [wins, draws, losses]; all = all time, rec = last 60 days. */\nwindow.OSTATS=%s;\n' % (time.strftime('%Y-%m-%d'), json.dumps(out, separators=(',', ':'))))
