# Builds ../clavados.js (Nov 23, his words: "I don't take a pawn with my queen because it looks defended, but the defender
# can't move — a bishop pins it to the king"). Lichess puzzle DB (CC0): the solver's first move CAPTURES something that has
# an attacker of the other side, but no legal recapture exists because the defender is pinned to its king.
# Usage (dir with lichess_db_puzzle.csv.zst + python-chess): python pinned.py <path>/curso.js <path>/debiles.js <out>/clavados.js
import csv, io, json, subprocess, sys, random, chess
random.seed(11)
def ids(path):
    s = open(path).read(); return set(__import__('re').findall(r'"([A-Za-z0-9]{5})"', s))
skip = ids(sys.argv[1]) | ids(sys.argv[2])
p = subprocess.Popen(['zstd', '-dc', 'lichess_db_puzzle.csv.zst'], stdout=subprocess.PIPE)
rd = csv.reader(io.TextIOWrapper(p.stdout, encoding='utf-8')); next(rd)
pool = []
for r in rd:
    pid, fen, moves, rating, rd_, pop, plays, themes = r[:8]
    rating, pop, plays = int(rating), int(pop), int(plays)
    if pid in skip or rating < 800 or rating > 1750 or pop < 80 or plays < 500: continue
    mv = moves.split()
    if len(mv) > 6: continue
    b = chess.Board(fen); b.push_uci(mv[0]); m = chess.Move.from_uci(mv[1])
    if not b.is_capture(m) or b.is_en_passant(m): continue
    me = b.turn; s = m.to_square; cap = b.piece_at(s)
    if cap is None or cap.piece_type == chess.KING: continue
    b2 = b.copy(); b2.push(m); opp = b2.turn
    att = [q for q in b2.attackers(opp, s)]
    if not att: continue
    if any(x.to_square == s for x in b2.legal_moves): continue          # a legal recapture exists -> not our theme
    if not any(b2.is_pinned(opp, q) for q in att): continue             # the reason must be a pin
    if b2.is_checkmate(): continue                                      # mate is another idea
    pool.append((pid, fen, mv, rating))
p.kill()
def san(fen, mv):
    b = chess.Board(fen); out = []
    for u in mv:
        x = chess.Move.from_uci(u); out.append(b.san(x)); b.push(x)
    return out
random.shuffle(pool); bands = {}
for x in pool: bands.setdefault(min(x[3] // 100, 20), []).append(x)
sel = []
for k in sorted(bands): sel += bands[k][:45]
rows = sorted([[pid, fen, ' '.join(san(fen, mv)), r] for pid, fen, mv, r in sel], key=lambda x: x[3])
print('pool', len(pool), '-> kept', len(rows), {k: len(v) for k, v in sorted(bands.items())})
open(sys.argv[3], 'w').write('/* Generated by tools/pinned.py from the Lichess puzzle database (CC0): capture a piece whose defender is pinned. Rows: [id, fen before the opponent move, SAN moves, rating]. */\nwindow.WEAKDB=window.WEAKDB||{};WEAKDB.pind=' + json.dumps(rows, separators=(',', ':')) + ';\n')
